class SegmentTree{
public:
    ll n;
    vector<ll>tree,lazy;
    SegmentTree(ll n){
        tree.resize(4*n);
        lazy.resize(4*n);
    }
    void build(ll node,ll l,ll r,vector<ll>&v){
        if(l == r){
            tree[node] = v[l];
            return;
        }
        ll mid = (l + r)/2;
        build(2*node,l,mid,v);
        build(2*node + 1,mid + 1,r,v);
        tree[node] = tree[2*node] + tree[2*node + 1];
    }
    void push(ll node,ll l,ll r){
        if(lazy[node]){
            tree[node] += (r - l + 1) * lazy[node];
            if(l!=r){
                lazy[2*node] += lazy[node];
                lazy[2*node + 1] += lazy[node];
            }
            lazy[node] = 0;
        }
    }
    void pointupdate(ll idx,ll val,ll l,ll r,ll node){
        push(node,l,r);
        if(idx < l || idx > r) return;
        if(l == r){
            tree[node] = val;
            return;
        }
        ll mid = (l + r)/2;
        pointupdate(idx,val,l,mid,2*node);
        pointupdate(idx,val,mid + 1,r,2*node + 1);
        tree[node] = tree[2*node] + tree[2*node + 1];
    }
    void rangeupdate(ll node,ll lq,ll rq,ll l,ll r,ll val){
        push(node,l,r);
        if(lq > r  || l > rq) return ;
        if(l >= lq && r <= rq){
            lazy[node] += val;
            push(node,l,r);
            return;
        }
        ll mid = (l + r)/2;
        rangeupdate(2*node,lq,rq,l,mid,val);
        rangeupdate(2*node + 1,lq,rq,mid + 1,r,val);
        tree[node] = tree[2*node] + tree[2*node + 1];
    }
    ll query(ll lq,ll rq,ll l ,ll r,ll node){
        push(node,l,r);
        if(lq > r  || l > rq) return 0;
        if(l >= lq && r <= rq) return tree[node];
        ll mid = (l + r)/2;
        return query(lq,rq,l,mid,2*node) + query(lq,rq,mid + 1,r,2*node + 1);
    }
};
void solve(){
    ll n,q,c;cin >> n >> q >> c;

    // v[tt][x][y] = total brightness at cell (x,y) at time tt (tt in 0..c)
    vector<vector<vector<ll>>> v(c + 1, vector<vector<ll>>(101, vector<ll>(101, 0)));

    // read stars and add their contribution to every time-layer tt
    loop(i,n){
        ll x,y,s;cin >> x >> y >> s;
        for(ll tt = 0; tt <= c; tt++){
            v[tt][x][y] += (s + tt) % (c + 1);
        }
    }

    // prefix sums for each time layer
    vector<vector<vector<ll>>> prefixsum(c + 1, vector<vector<ll>>(101, vector<ll>(101, 0)));
    for(ll tt = 0; tt <= c; tt++){
        for(ll x = 1; x <= 100; x++){
            for(ll y = 1; y <= 100; y++){
                prefixsum[tt][x][y] = v[tt][x][y] + prefixsum[tt][x][y - 1] + prefixsum[tt][x - 1][y] - prefixsum[tt][x - 1][y - 1];
            }
        }
    }

    // answer queries
    loop(i,q){
        ll t,x1,y1,x2,y2;cin >> t >> x1 >> y1 >> x2 >> y2;
        ll tt = t % (c + 1);
        ll ans = prefixsum[tt][x2][y2] - prefixsum[tt][x1 - 1][y2] - prefixsum[tt][x2][y1 - 1] + prefixsum[tt][x1 - 1][y1 - 1];
        cout << ans << '\n';
    }
}
